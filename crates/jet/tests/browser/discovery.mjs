import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

export async function catalogueAndSafeDiscovery({ page, app, fixtureUrl, artifacts }) {
  await mkdir(artifacts, { recursive: true });
  const control = async value => { const response = await fetch(new URL('test/control', fixtureUrl), { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) }); assert.equal(response.status, 200); };
  const state = async () => (await fetch(new URL('test/state', fixtureUrl))).json();
  const waitState = async predicate => { for (let attempt = 0; attempt < 100; attempt++) { const value = await state(); if (predicate(value)) return value; await new Promise(resolve => setTimeout(resolve, 30)); } throw new Error('Fixture state did not settle'); };
  const browse = async name => {
    const back = page.getByRole('button', { name: 'Catalogue', exact: true });
    if (await back.isVisible()) await back.click();
    await page.getByLabel('Search tools', { exact: true }).fill('');
    const detail = page.locator(`.tool-summary[data-tool="${name}"]`);
    if (await detail.getAttribute('open') === null) await detail.locator('summary').click();
    await detail.getByRole('button', { name: 'Browse ' + name, exact: true }).click();
  };
  const discovery = page.locator('.discovery-view');
  const status = page.locator('.tools-status');
  await page.getByRole('button', { name: 'Jet', exact: true }).click();
  await page.locator('#field').fill('/tools');
  await page.locator('#field').press('Enter');
  await page.getByLabel('Tool app', { exact: true }).selectOption(app.id);
  await page.getByText('fixture-notebook 1.0.0', { exact: true }).waitFor();
  await page.getByText('Protocol: 2025-11-25', { exact: true }).waitFor();
  await page.getByText('Server instructions and capabilities', { exact: true }).click();
  assert.match(await page.locator('.tools-server').innerText(), /Use collections/);
  await page.getByLabel('Search tools', { exact: true }).fill('read a fixture');
  assert.equal(await page.locator('.tool-summary').count(), 1);
  await browse('collections');
  await page.getByRole('button', { name: 'Expand Examples', exact: true }).click();
  await page.getByRole('button', { name: 'Inspect Welcome note', exact: true }).click();
  assert.match(await discovery.innerText(), /read_note/);
  assert.match(await discovery.innerText(), /welcome/);
  assert.match(await discovery.innerText(), /Output schema/);
  await page.screenshot({ path: artifacts + '/tools-leaf.png' });
  assert.equal((await state()).calls.some(call => call.name === 'read_note'), false);
  const beforeDraft = (await state()).calls.length;
  let modelRequests = 0;
  const track = request => { if (/\/api\/(chat\/send|feel)$/.test(new URL(request.url()).pathname)) modelRequests++; };
  page.on('request', track);
  await discovery.getByRole('button', { name: 'Ask Jet about read_note', exact: true }).click();
  assert.match(await page.locator('#field').inputValue(), new RegExp(app.id));
  assert.match(await page.locator('#field').inputValue(), /read_note.*welcome/);
  assert.equal((await state()).calls.length, beforeDraft);
  assert.equal(modelRequests, 0);
  page.off('request', track);
  await page.getByRole('button', { name: 'Jet', exact: true }).click();
  await page.locator('#field').fill('/tools');
  await page.locator('#field').press('Enter');
  await page.getByLabel('Tool app', { exact: true }).selectOption(app.id);
  await page.getByText('fixture-notebook 1.0.0', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Browse search', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Browse future', exact: true }).count(), 0);

  await page.getByText('6 tools available', { exact: true }).waitFor();
  assert.ok(await page.locator('.tools-catalogue button').count() > 0);
  let releaseApps;
  const appsBlocked = new Promise(resolve => { releaseApps = resolve; });
  await page.route('**/api/apps', async route => { await appsBlocked; await route.continue(); });
  await page.getByLabel('Tool app', { exact: true }).selectOption('');
  await page.getByText('Loading apps…', { exact: true }).waitFor();
  try {
    assert.equal(await page.locator('.tools-catalogue button').count(), 0, 'Previous app actions disappear while the next scope loads');
  } finally { releaseApps(); }
  await page.getByText('Choose an app to inspect its tools.', { exact: true }).waitFor();
  await page.unroute('**/api/apps');
  await page.getByLabel('Tool app', { exact: true }).selectOption(app.id);
  await page.getByText('fixture-notebook 1.0.0', { exact: true }).waitFor();

  await control({ mode: 'unsupported' });
  await browse('collections');
  await page.getByText('Unsupported targets were not called.', { exact: true }).waitFor();
  assert.equal(await discovery.getByRole('button', { name: /^Expand / }).count(), 0);
  assert.equal((await state()).calls.some(call => ['search', 'future', 'absent'].includes(call.name)), false);
  await control({ mode: 'invalid' });
  const notesBefore = (await state()).calls.filter(call => call.name === 'notes').length;
  await browse('collections');
  await page.getByRole('button', { name: 'Expand Invalid arguments', exact: true }).click();
  await page.getByText(/^Discovery failed:/).waitFor();
  assert.equal((await state()).calls.filter(call => call.name === 'notes').length, notesBefore);

  await control({ mode: 'cycle' });
  await browse('collections');
  const cycleCount = (await state()).calls.length;
  await page.getByRole('button', { name: 'Expand Again', exact: true }).click();
  await page.getByText('Discovery cycle stopped.', { exact: true }).waitFor();
  assert.equal((await state()).calls.length, cycleCount);
  await browse('paths');
  for (let depth = 1; depth <= 16; depth++) await page.getByRole('button', { name: 'Expand Next ' + depth, exact: true }).click();
  await page.getByText('Discovery depth limit reached (16).', { exact: true }).waitFor();
  assert.equal((await state()).calls.filter(call => call.name === 'paths').length, 16);

  await control({ mode: 'overflow' });
  await browse('collections');
  await page.getByText('Showing the first 200 nodes. Result limit reached.', { exact: true }).waitFor();
  assert.equal(await discovery.getByRole('button', { name: /^Inspect Note / }).count(), 200);
  await control({ mode: 'raw' });
  await browse('collections');
  await page.getByText('Unsupported discovery result. Raw data is available below.', { exact: true }).waitFor();
  await discovery.getByText('Raw result', { exact: true }).click();
  await page.getByText('Raw result truncated at 256 KiB.', { exact: true }).waitFor();
  assert.ok(Buffer.byteLength(await discovery.locator('pre').innerText()) <= 256 * 1024);
  await control({ mode: 'tool_error' });
  await browse('collections');
  await page.getByText('Discovery returned a tool error.', { exact: true }).waitFor();
  assert.equal(await discovery.getByRole('button', { name: /^Expand / }).count(), 0);
  await control({ mode: 'error' });
  await browse('collections');
  await page.getByText(/^Discovery failed:/).waitFor();

  await control({ mode: 'normal', blockTool: 'collections' });
  const cancelledBefore = (await state()).cancellations.length;
  await browse('collections');
  await waitState(value => value.blocked.length > 0);
  await page.getByRole('button', { name: 'Cancel discovery', exact: true }).click();
  await page.getByText('Discovery cancelled.', { exact: true }).waitFor();
  await waitState(value => value.cancellations.length > cancelledBefore);
  await control({ release: true, blockTool: null });
  await page.waitForTimeout(100);
  assert.equal(await discovery.getByRole('button', { name: 'Expand Examples', exact: true }).count(), 0);
  await control({ blockTool: 'collections' });
  await browse('collections');
  await waitState(value => value.blocked.length > 0);
  await page.getByLabel('Tool app', { exact: true }).selectOption('');
  await control({ release: true, blockTool: null });
  await page.getByText('Choose an app to inspect its tools.', { exact: true }).waitFor();
  assert.equal(await discovery.isVisible(), false);

  await page.getByLabel('Tool app', { exact: true }).selectOption(app.id);
  await page.getByText('fixture-notebook 1.0.0', { exact: true }).waitFor();
  await control({ offline: true });
  await page.getByRole('button', { name: 'Refresh tools', exact: true }).click();
  await page.getByText(/^Stale metadata:/).waitFor();
  assert.ok(await page.locator('.tool-summary').count() > 0);
  await control({ offline: false });
  await page.getByRole('button', { name: 'Refresh tools', exact: true }).click();
  await page.getByText('6 tools available', { exact: true }).waitFor();
  await page.route('**/api/apps/' + app.id + '/tools', route => route.abort('failed'));
  await page.getByRole('button', { name: 'Refresh tools', exact: true }).click();
  await page.getByText(/^Stale metadata:/).waitFor();
  assert.ok(await page.locator('.tool-summary').count() > 0);
  await page.unroute('**/api/apps/' + app.id + '/tools');
  await page.getByRole('button', { name: 'Refresh tools', exact: true }).click();
  await page.getByText('6 tools available', { exact: true }).waitFor();
  assert.equal((await state()).calls.some(call => ['search', 'future', 'read_note'].includes(call.name)), false);
  assert.match(await status.innerText(), /available/);

  await mkdir(artifacts, { recursive: true });
  await page.screenshot({ path: artifacts + '/tools-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: artifacts + '/tools-narrow.png' });
  const geometry = await page.locator('#tools-content').evaluate(element => ({ scroll: element.scrollWidth, width: element.clientWidth, buttons: [...element.querySelectorAll('button')].filter(button => button.offsetParent).map(button => ({ left: button.getBoundingClientRect().left, right: button.getBoundingClientRect().right })) }));
  assert.ok(geometry.scroll <= geometry.width + 1);
  assert.ok(geometry.buttons.every(button => button.left >= 0 && button.right <= 391));
  await page.setViewportSize({ width: 1440, height: 900 });
}
